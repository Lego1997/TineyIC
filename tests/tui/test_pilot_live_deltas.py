async def test_c_system_interrupt_badge_shows_provenance_not_esc():
    q: queue.Queue = queue.Queue()
    app = TownHallApp.live(q, auto_replay=False)
    async with app.run_test() as pilot:
        await pilot.pause()
        for ev in (
            _ev("debate_started", ticker="T", personas=[{"name": "Solo"}]),
            _ev("phase_started", phase="opening", index=0),
            _ev("turn_started", turn_id="t1", persona="Solo",
                phase="opening", role="statement"),
            _ev("think_delta", turn_id="t1", text="mid thought"),
            # A provider/system interrupt — NOT the user's esc affordance.
            _ev("turn_interrupted", turn_id="t1", persona="Solo",
                by="system", disposition="discarded_on_arrival"),
        ):
            q.put(ev)
        app.replay_all_now()
        await pilot.pause()

        card = _card(app, "t1")
        assert card.turn.interrupted is True
        assert card.turn.interrupted_by == "system"
        assert card.turn.thinking_live is False       # interrupt clears the block
        assert card._think_live.display is False
        head = str(card._head.render())
        assert "interrupted" in head
        assert "(system)" in head
        assert "(esc)" not in head                     # not mislabelled as user esc
        assert "discarded_on_arrival" in head


async def test_c_esc_with_no_active_turn_records_request_with_null_turn():
    q: queue.Queue = queue.Queue()
    app = TownHallApp.live(q, auto_replay=False)
    async with app.run_test() as pilot:
        await pilot.pause()
        assert isinstance(app._control, RecordingControlSink)
        # Only lifecycle folded — no speaker is active.
        for ev in (
            _ev("debate_started", ticker="T", personas=[{"name": "Solo"}]),
            _ev("phase_started", phase="opening", index=0),
        ):
            q.put(ev)
        app.replay_all_now()
        await pilot.pause()
        assert app.state.current_turn_id is None

        await pilot.press("escape")
        await pilot.pause()

        # The request still goes through the sink (never a fabricated interrupt),
        # carrying a null turn_id since there was no current speaker.
        assert len(app._control.requests) == 1
        assert app._control.requests[0].turn_id is None
        assert app._control.requests[0].source == "tui"
        # No transcript turn was invented, nothing marked interrupted.
        assert _turn_count(app) == 0


# --------------------------------------------------------------------------- #
# (d) A JSONL follower feeds the UI live; mid-test appends appear; truncated
#     tail is tolerated, then cleanly reassembled.
# --------------------------------------------------------------------------- #

async def test_d_follower_feeds_ui_incrementally_and_tolerates_truncated_tail(tmp_path):
    path = tmp_path / "run.jsonl"
    # Pre-existing prefix at attach time: a debate + one full streamed turn (t1),
    # no terminal event yet (the debate is still running in another process).
    path.write_text(
        _line(_env(1, "debate_started", ticker="AAPL",
                   personas=[{"name": "Warren Buffett"}]))
        + _line(_env(2, "phase_started", phase="opening", index=0))
        + _line(_env(3, "turn_started", turn_id="t1", persona="Warren Buffett",
                     phase="opening", role="statement"))
        + _line(_env(4, "think_delta", turn_id="t1", text="weighing the moat"))
        + _line(_env(5, "talk_delta", turn_id="t1", text="I would buy."))
        + _line(_env(6, "talk_completed", turn_id="t1", full_text="I would buy."))
        + _line(_env(7, "turn_completed", turn_id="t1", persona="Warren Buffett",
                     phase="opening", interrupted=False)),
        encoding="utf-8",
    )

    q: queue.Queue = queue.Queue()
    follower = attach_event_log_follower(path, q, poll_interval=0.01)
    app = TownHallApp.live(q, auto_replay=False)
    try:
        async with app.run_test() as pilot:
            await pilot.pause()

            # The pre-existing prefix streams into the UI, whole turn and all.
            assert await _drain_until(
                app, pilot, lambda: _turn_speech(app, "t1") == "I would buy."
            )
            assert app.state.ticker == "AAPL"
            assert _card(app, "t1").turn.speech == "I would buy."
            assert app.state.finished is False        # no terminal yet

            # Mid-test: append a SECOND turn (t2) plus a truncated final record —
            # bytes with no closing newline, exactly what a crash mid-write leaves.
            _append(path, _line(_env(8, "turn_started", turn_id="t2",
                                     persona="Warren Buffett", phase="opening",
                                     role="statement")))
            _append(path, _line(_env(9, "think_delta", turn_id="t2",
                                     text="second thought")))
            _append(path, _line(_env(10, "talk_completed", turn_id="t2",
                                     full_text="I hold.")))
            _append(path, _line(_env(11, "turn_completed", turn_id="t2",
                                     persona="Warren Buffett", phase="opening",
                                     interrupted=False)))
            _append(path, '{"v":1,"seq":12,"type":"talk_de')  # half-written line

            # t2 lands in full; the partial line is held in the follower's buffer,
            # so it neither crashes the UI nor fabricates a third turn.
            assert await _drain_until(
                app, pilot, lambda: _turn_speech(app, "t2") == "I hold."
            )
            assert _card(app, "t2").turn.speech == "I hold."
            assert _turn_count(app) == 2
            assert app.state.finished is False

            # Complete the partial record (reassembled into a valid, no-op delta),
            # then a terminal event: the debate finishes cleanly, no turn lost or
            # invented, the truncated bytes never corrupting the stream.
            _append(path, 'lta","payload":{"turn_id":"t2","text":""}}\n')
            _append(path, _line(_env(13, "debate_completed",
                                     phases_completed=["opening"],
                                     duration_s=1.0, result_ref="x")))

            assert await _drain_until(app, pilot, lambda: app.state.finished)
            assert _turn_count(app) == 2
            assert _card(app, "t2").turn.speech == "I hold."
            header = str(app.query_one(StatusHeader).render()).lower()
            assert "complete" in header
    finally:
        follower.stop()
        follower.join(timeout=5.0)
